/** Inline SVG icon (stroke style). Markup is static and trusted. */
export function icon(name, size = 18) {
  const span = document.createElement('span');
  span.className = 'ico';
  span.setAttribute('aria-hidden', 'true');
  span.innerHTML = `<svg viewBox="0 0 24 24" width="${size}" height="${size}" fill="none" stroke="currentColor" stroke-width="1.8" stroke-linecap="round" stroke-linejoin="round">${PATHS[name] || ''}</svg>`;
  return span;
}

let toastHost;
/** Show a short message. `action` = { label, run } adds a button (e.g. Undo). */
export function toast(message, action, ms = 5000) {
  if (!toastHost) {
    toastHost = h('div.toast-host', { role: 'status', 'aria-live': 'polite' });
    document.body.append(toastHost);
  }
  const el = h('div.toast', h('span', message));
  let timer;
  const close = () => { clearTimeout(timer); el.remove(); };
  if (action) {
    el.append(h('button', { type: 'button', onclick: () => { close(); action.run(); } }, action.label));
  }
  el.append(h('button', { type: 'button', 'aria-label': 'Dismiss', onclick: close }, '×'));
  toastHost.append(el);
  timer = setTimeout(close, ms);
  return close;
}

/** Apply the theme setting (auto | light | dark) to <html>. */
export function applyTheme(theme) {
  const root = document.documentElement;
  if (theme === 'light' || theme === 'dark') root.dataset.theme = theme;
  else delete root.dataset.theme;
}

export function debounce(fn, ms) {
  let t;
  const d = (...a) => { clearTimeout(t); t = setTimeout(() => fn(...a), ms); };
  d.flush = (...a) => { clearTimeout(t); fn(...a); };
  return d;
}

/** True when a key event happens while typing in a field, so global shortcuts should not fire. */
export function isTyping(e) {
  const t = e.target;
  return !!(t && (t.isContentEditable || /^(INPUT|TEXTAREA|SELECT)$/.test(t.tagName)));
}

/** Open an extension page in a new tab (from the popup), or navigate the current page. */
export async function openPage(path, { newTab = true } = {}) {
  const url = chrome.runtime.getURL(path);
  if (!newTab) { location.href = url; return; }
  await chrome.tabs.create({ url });
}

/** Simple confirm dialog that returns a promise. */
export function confirmDialog(message, okLabel = 'Delete') {
  return new Promise((resolve) => {
    const dlg = h('dialog', { 'aria-label': 'Confirm' },
      h('form.dialog-body', { method: 'dialog' },
        h('p', { style: { margin: 0 } }, message),
        h('div.dialog-foot',
          h('button.btn', { value: 'cancel', type: 'submit' }, 'Cancel'),
          h('button.btn.primary', { value: 'ok', type: 'submit' }, okLabel))));
    dlg.addEventListener('close', () => { resolve(dlg.returnValue === 'ok'); dlg.remove(); });
    document.body.append(dlg);
    dlg.showModal();
  });
}
