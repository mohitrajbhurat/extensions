export function $(sel, root = document) { return root.querySelector(sel); }

export function el(tag, attrs = {}, ...children) {
  const n = document.createElement(tag);
  for (const [k, v] of Object.entries(attrs)) {
    if (v == null || v === false) continue;
    if (k === 'class') n.className = v;
    else if (k === 'html') n.innerHTML = v;
    else if (k === 'text') n.textContent = v;
    else if (k.startsWith('on')) n.addEventListener(k.slice(2), v);
    else n.setAttribute(k, v === true ? '' : v);
  }
  for (const c of children.flat()) if (c != null) n.append(c);
  return n;
}

const LETTER_COLORS = ['#7c3aed', '#2563eb', '#0d9488', '#d97706', '#db2777', '#4f46e5', '#059669', '#dc2626'];

/** Favicon <img> backed by the browser's favicon cache, with a letter tile fallback. */
export function favicon(url, domain) {
  const img = el('img', { class: 'favicon', alt: '', width: 16, height: 16, loading: 'lazy', src: faviconUrl(url, 32) });
  img.addEventListener('error', () => {
    const letter = (domain || '?').replace(/^www\./, '')[0] || '?';
    let h = 0; for (const c of domain || '') h = (h * 31 + c.charCodeAt(0)) >>> 0;
    const span = el('span', { class: 'favicon letter', 'aria-hidden': 'true', text: letter.toUpperCase() });
    span.style.background = LETTER_COLORS[h % LETTER_COLORS.length];
    img.replaceWith(span);
  }, { once: true });
  return img;
}

let toastTimer = null;
export function toast(message, action) {
  document.querySelector('.toast')?.remove();
  clearTimeout(toastTimer);
  const t = el('div', { class: 'toast', role: 'status' }, el('span', { text: message }));
  if (action) t.append(el('button', { class: 'btn', type: 'button', text: action.label, onclick: () => { t.remove(); action.run(); } }));
  document.body.append(t);
  toastTimer = setTimeout(() => t.remove(), action ? 6000 : 3000);
}
