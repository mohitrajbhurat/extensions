export const TRACKER_DOMAINS = Object.keys(TRACKERS);

export const DOMAINS_BY_CATEGORY = (() => {
  const out = {};
  for (const id of CATEGORY_IDS) out[id] = [];
  for (const [domain, category] of Object.entries(TRACKERS)) {
    if (out[category]) out[category].push(domain);
  }
  for (const id of CATEGORY_IDS) out[id].sort();
  return out;
})();

/** Longest-suffix lookup: "px.ads.linkedin.com" -> "linkedin.com". */
export function trackerDomainOf(hostname) {
  if (!hostname) return null;
  const host = hostname.toLowerCase().replace(/\.$/, '');
  if (TRACKERS[host]) return host;
  const parts = host.split('.');
  for (let i = 1; i < parts.length - 1; i++) {
    const candidate = parts.slice(i).join('.');
    if (TRACKERS[candidate]) return candidate;
  }
  return null;
}

export function categoryOf(hostname) {
  const domain = trackerDomainOf(hostname);
  return domain ? TRACKERS[domain] : null;
}

export function ownerOf(domain) {
  return OWNERS[domain] || null;
}

/** Display label: "doubleclick.net (Google)". */
export function describeDomain(domain) {
  const owner = OWNERS[domain];
  return owner ? `${domain} · ${owner}` : domain;
}
