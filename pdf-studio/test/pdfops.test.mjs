// Node test for page operations. Run: node pdf-studio/test/pdfops.test.mjs
// Generates PDFs with pdf-lib, runs merge/split/rotate/etc. and checks page counts and rotations.
import { createRequire } from 'node:module';
import assert from 'node:assert/strict';
import { readFileSync } from 'node:fs';

const require = createRequire(import.meta.url);
globalThis.PDFLib = require('../vendor/pdf-lib.min.js');
const PDFLib = globalThis.PDFLib;
const ops = await import('../lib/pdfops.js');
const { parseRanges } = await import('../lib/common.js');

async function makePdf(n, label = 'Doc', size = [612, 792]) {
  const doc = await PDFLib.PDFDocument.create();
  const font = await doc.embedFont(PDFLib.StandardFonts.Helvetica);
  for (let i = 0; i < n; i++) {
    const p = doc.addPage(size);
    p.drawText(`${label} page ${i + 1}`, { x: 50, y: size[1] - 80, size: 24, font });
  }
  return doc.save();
}

async function info(bytes) {
  const doc = await PDFLib.PDFDocument.load(bytes);
  return {
    count: doc.getPageCount(),
    rotations: doc.getPages().map((p) => p.getRotation().angle),
    sizes: doc.getPages().map((p) => [Math.round(p.getWidth()), Math.round(p.getHeight())])
  };
}

let passed = 0;
async function test(name, fn) {
  try {
    await fn();
    passed++;
    console.log('ok   ' + name);
  } catch (e) {
    console.error('FAIL ' + name + '\n', e);
    process.exitCode = 1;
  }
}

const a = await makePdf(3, 'A');
const b = await makePdf(5, 'B', [595, 842]);
const c = await makePdf(1, 'C');

await test('merge 3 + 5 + 1 = 9 pages', async () => {
  const out = await ops.merge([a, b, c]);
  const i = await info(out);
  assert.equal(i.count, 9);
  assert.deepEqual(i.sizes[3], [595, 842]);
  assert.deepEqual(i.sizes[8], [612, 792]);
});

await test('merge with page selections', async () => {
  const out = await ops.merge([a, b], [[0], [4, 3]]);
  assert.equal((await info(out)).count, 3);
});

await test('split every 2 pages: 5 -> 2,2,1', async () => {
  const parts = await ops.splitEvery(b, 2);
  assert.equal(parts.length, 3);
  assert.deepEqual(await Promise.all(parts.map(async (p) => (await info(p)).count)), [2, 2, 1]);
});

await test('split by ranges "1-2, 4, 3-5"', async () => {
  const groups = parseRanges('1-2, 4, 3-5', 5);
  assert.deepEqual(groups, [[0, 1], [3], [2, 3, 4]]);
  const parts = await ops.splitGroups(b, groups);
  assert.deepEqual(await Promise.all(parts.map(async (p) => (await info(p)).count)), [2, 1, 3]);
});

await test('parseRanges rejects out-of-range and junk', async () => {
  assert.throws(() => parseRanges('0-2', 5));
  assert.throws(() => parseRanges('7', 5));
  assert.throws(() => parseRanges('abc', 5));
  assert.deepEqual(parseRanges('4-', 5), [[3, 4]]);
});

await test('rotate all by 90, then selected by -90', async () => {
  const r1 = await ops.rotate(a, 90);
  assert.deepEqual((await info(r1)).rotations, [90, 90, 90]);
  const r2 = await ops.rotate(r1, -90, [1]);
  assert.deepEqual((await info(r2)).rotations, [90, 0, 90]);
  const r3 = await ops.rotate(r1, 270, [0]);
  assert.deepEqual((await info(r3)).rotations, [0, 90, 90]);
});

await test('delete pages 2 and 4 of 5', async () => {
  const out = await ops.removePages(b, [1, 3]);
  assert.equal((await info(out)).count, 3);
  await assert.rejects(() => ops.removePages(c, [0]));
});

await test('extract and reorder', async () => {
  assert.equal((await info(await ops.extract(b, [4, 0]))).count, 2);
  const re = await ops.reorder(a, [2, 1, 0]);
  const doc = await PDFLib.PDFDocument.load(re);
  assert.equal(doc.getPageCount(), 3);
});

await test('insert blank page', async () => {
  const out = await ops.insertBlank(a, 1);
  assert.equal((await info(out)).count, 4);
});

await test('buildFromPlan: reorder + rotate + blank + duplicate across sources', async () => {
  const out = await ops.buildFromPlan([a, b], [
    { src: 1, page: 4 },
    { src: 0, page: 0, rotate: 90 },
    { blank: true, size: [300, 300] },
    { src: 0, page: 0 },
    { src: 1, page: 0, rotate: -90 }
  ]);
  const i = await info(out);
  assert.equal(i.count, 5);
  assert.deepEqual(i.rotations, [0, 90, 0, 0, 270]);
  assert.deepEqual(i.sizes[2], [300, 300]);
});

await test('images to PDF (PNG) on A4 and fit', async () => {
  // Minimal 2x1 PNG generated by pdf-lib-independent bytes.
  const png = Buffer.from('iVBORw0KGgoAAAANSUhEUgAAAAIAAAABCAYAAAD0In+KAAAAEUlEQVR4nGP4z8DwnwEIGAAZAgH/1W6nWQAAAABJRU5ErkJggg==', 'base64');
  const out = await ops.imagesToPdf([{ bytes: png, type: 'png' }, { bytes: png, type: 'png' }], { pageSize: 'a4', margin: 36 });
  const i = await info(out);
  assert.equal(i.count, 2);
  assert.deepEqual(i.sizes[0], [842, 595]); // landscape auto for wide image
  const fit = await ops.imagesToPdf([{ bytes: png, type: 'png' }], { pageSize: 'fit' });
  assert.equal((await info(fit)).count, 1);
});

await test('compress re-save keeps pages', async () => {
  const big = await ops.merge([a, b, a, b]);
  const out = await ops.compressResave(big);
  assert.equal((await info(out)).count, 16);
});

await test('compress keeps AcroForm fields; inspect reports pages', async () => {
  const doc = await PDFLib.PDFDocument.create();
  const page = doc.addPage([300, 300]);
  const tf = doc.getForm().createTextField('name');
  tf.setText('Ada');
  tf.addToPage(page, { x: 20, y: 200, width: 150, height: 24 });
  const out = await ops.compressResave(await doc.save());
  const back = await PDFLib.PDFDocument.load(out);
  assert.equal(back.getForm().getTextField('name').getText(), 'Ada');
  assert.deepEqual(await ops.inspect(out), { pages: 1, encrypted: false });
});

await test('zip writer produces a valid archive header and CRC', async () => {
  const { makeZip, crc32 } = await import('../lib/zip.js');
  assert.equal(crc32(new TextEncoder().encode('123456789')), 0xcbf43926);
  const zip = makeZip([{ name: 'a.pdf', bytes: a }, { name: 'b.pdf', bytes: b }]);
  const v = new DataView(zip.buffer);
  assert.equal(v.getUint32(0, true), 0x04034b50);
  assert.equal(v.getUint32(zip.length - 22, true), 0x06054b50);
  assert.equal(v.getUint16(zip.length - 12, true), 2);
});

await test('wrapText breaks long lines and words', async () => {
  const { wrapText } = await import('../lib/annogeom.js');
  const lines = wrapText('hello world foo\nsupercalifragilistic', 11, (s) => s.length);
  assert.deepEqual(lines, ['hello world', 'foo', 'supercalifr', 'agilistic']);
});

console.log(`\n${passed} tests passed${process.exitCode ? ', some FAILED' : ''}`);
